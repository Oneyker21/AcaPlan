BEGIN;

CREATE TABLE IF NOT EXISTS public.pwa_departamentos (
  id_departamento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL UNIQUE,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (char_length(trim(nombre)) BETWEEN 1 AND 100)
);

CREATE TABLE IF NOT EXISTS public.pwa_departamento_jefaturas (
  id_departamento INTEGER NOT NULL REFERENCES public.pwa_departamentos(id_departamento),
  id_usuario INTEGER NOT NULL REFERENCES public.usuarios(id_usuario) ON DELETE CASCADE,
  asignado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (id_departamento, id_usuario)
);
CREATE UNIQUE INDEX IF NOT EXISTS pwa_departamento_jefatura_unica
  ON public.pwa_departamento_jefaturas(id_usuario);

CREATE TABLE IF NOT EXISTS public.pwa_departamento_asignaturas (
  id_departamento INTEGER NOT NULL REFERENCES public.pwa_departamentos(id_departamento),
  id_asignatura INTEGER NOT NULL REFERENCES public.asignaturas(id_asignatura),
  PRIMARY KEY (id_departamento, id_asignatura)
);

CREATE TABLE IF NOT EXISTS public.pwa_docente_departamentos (
  id_departamento INTEGER NOT NULL REFERENCES public.pwa_departamentos(id_departamento),
  id_docente INTEGER NOT NULL REFERENCES public.docentes(id_docente) ON DELETE CASCADE,
  registrado_por INTEGER NOT NULL REFERENCES public.usuarios(id_usuario),
  registrado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (id_departamento, id_docente)
);

-- La modalidad pertenece al docente, no al departamento: puede compartirse
-- entre departamentos y conservar un solo tipo (planta u horario).
CREATE TABLE IF NOT EXISTS public.pwa_docente_tipo (
  id_docente INTEGER PRIMARY KEY REFERENCES public.docentes(id_docente) ON DELETE CASCADE,
  tipo_docente TEXT NOT NULL CHECK (tipo_docente IN ('planta', 'horario')),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.pwa_docente_asignaturas (
  id_departamento INTEGER NOT NULL,
  id_docente INTEGER NOT NULL,
  id_asignatura INTEGER NOT NULL,
  PRIMARY KEY (id_departamento, id_docente, id_asignatura),
  FOREIGN KEY (id_departamento, id_docente)
    REFERENCES public.pwa_docente_departamentos(id_departamento, id_docente) ON DELETE CASCADE,
  FOREIGN KEY (id_departamento, id_asignatura)
    REFERENCES public.pwa_departamento_asignaturas(id_departamento, id_asignatura)
);

ALTER TABLE public.pwa_departamentos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pwa_departamento_jefaturas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pwa_departamento_asignaturas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pwa_docente_departamentos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pwa_docente_tipo ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pwa_docente_asignaturas ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.pwa_departamentos, public.pwa_departamento_jefaturas,
  public.pwa_departamento_asignaturas, public.pwa_docente_departamentos,
  public.pwa_docente_tipo, public.pwa_docente_asignaturas FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.pwa_jefatura_academica(action TEXT, payload JSONB DEFAULT '{}')
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  _caller UUID := auth.uid();
  _profile RECORD;
  _admin BOOLEAN := FALSE;
  _department INTEGER;
  _target_department INTEGER;
  _target_user INTEGER;
  _teacher INTEGER;
  _subject_ids INTEGER[];
  _count INTEGER;
  _name TEXT;
  _email TEXT;
  _cedula TEXT;
  _teacher_type TEXT;
  _result JSONB;
BEGIN
  IF _caller IS NULL THEN RAISE EXCEPTION 'PERMISO_DENEGADO'; END IF;
  SELECT u.id_usuario, u.correo, u.rol, u.estado
    INTO _profile
    FROM public.usuarios u
   WHERE lower(u.correo) = lower((SELECT au.email FROM auth.users au WHERE au.id = _caller))
     AND u.estado = 'activo'
   LIMIT 1;
  IF _profile.id_usuario IS NULL THEN RAISE EXCEPTION 'PERMISO_DENEGADO'; END IF;
  _admin := _profile.rol = 'administrador';

  SELECT j.id_departamento INTO _department
    FROM public.pwa_departamento_jefaturas j
    JOIN public.pwa_departamentos d ON d.id_departamento = j.id_departamento AND d.activo
   WHERE j.id_usuario = _profile.id_usuario
     AND EXISTS (
       SELECT 1 FROM public.pwa_permisos_usuario p
        WHERE p.id_usuario = _profile.id_usuario
          AND 'jefe_departamento' = ANY(p.funciones)
     );

  IF action = 'context' THEN
    RETURN jsonb_build_object(
      'isAdmin', _admin,
      'canManageDepartments', _admin,
      'canManageDepartmentTeachers', _department IS NOT NULL,
      'id_departamento', _department,
      'departamento', (SELECT d.nombre FROM public.pwa_departamentos d WHERE d.id_departamento = _department AND d.activo)
    );
  END IF;

  IF action = 'departments.list' THEN
    IF NOT _admin AND _department IS NULL THEN RAISE EXCEPTION 'PERMISO_DENEGADO'; END IF;
    SELECT coalesce(jsonb_agg(
      jsonb_build_object(
        'id_departamento', d.id_departamento,
        'nombre', d.nombre,
        'activo', d.activo,
        'id_jefe', h.id_usuario,
        'jefe_nombre', u.nombre,
        'id_asignaturas', (SELECT coalesce(jsonb_agg(da.id_asignatura ORDER BY a.codigo), '[]'::jsonb)
          FROM public.pwa_departamento_asignaturas da
          JOIN public.asignaturas a ON a.id_asignatura = da.id_asignatura
         WHERE da.id_departamento = d.id_departamento),
        'componentes', (SELECT coalesce(jsonb_agg(jsonb_build_object('id_asignatura', a.id_asignatura, 'codigo', a.codigo, 'nombre', a.nombre) ORDER BY a.codigo), '[]'::jsonb)
          FROM public.pwa_departamento_asignaturas da
          JOIN public.asignaturas a ON a.id_asignatura = da.id_asignatura
         WHERE da.id_departamento = d.id_departamento)
      ) ORDER BY d.nombre
    ), '[]'::jsonb)
      INTO _result
      FROM public.pwa_departamentos d
      LEFT JOIN public.pwa_departamento_jefaturas h ON h.id_departamento = d.id_departamento
      LEFT JOIN public.usuarios u ON u.id_usuario = h.id_usuario
     WHERE (_admin OR d.id_departamento = _department);
    RETURN _result;
  END IF;

  IF action IN ('departments.save', 'departments.assign_head', 'departments.set_subjects') THEN
    IF NOT _admin THEN RAISE EXCEPTION 'PERMISO_DENEGADO'; END IF;
    IF action = 'departments.save' THEN
      _name := trim(payload->>'nombre');
      IF _name IS NULL OR char_length(_name) NOT BETWEEN 1 AND 100 THEN RAISE EXCEPTION 'DATOS_INVALIDOS'; END IF;
      IF payload->>'id' IS NULL THEN
        INSERT INTO public.pwa_departamentos(nombre) VALUES (_name) RETURNING id_departamento INTO _target_department;
      ELSE
        _target_department := (payload->>'id')::INTEGER;
        UPDATE public.pwa_departamentos
           SET nombre = _name,
               activo = coalesce((payload->>'activo')::BOOLEAN, activo),
               actualizado_en = now()
         WHERE id_departamento = _target_department;
        IF NOT FOUND THEN RAISE EXCEPTION 'NO_ENCONTRADO'; END IF;
      END IF;
      RETURN jsonb_build_object('ok', TRUE, 'id', _target_department);
    END IF;
    _target_department := (payload->>'id_departamento')::INTEGER;
    IF NOT EXISTS (SELECT 1 FROM public.pwa_departamentos WHERE id_departamento = _target_department AND activo) THEN RAISE EXCEPTION 'DEPARTAMENTO_INVALIDO'; END IF;
    IF action = 'departments.assign_head' THEN
      IF payload->>'id_usuario' IS NULL OR payload->>'id_usuario' = '' THEN
        DELETE FROM public.pwa_departamento_jefaturas WHERE id_departamento = _target_department;
      ELSE
        _target_user := (payload->>'id_usuario')::INTEGER;
        IF NOT EXISTS (
          SELECT 1 FROM public.usuarios u
          JOIN public.pwa_permisos_usuario p ON p.id_usuario = u.id_usuario
            AND 'jefe_departamento' = ANY(p.funciones)
          WHERE u.id_usuario = _target_user AND u.rol = 'docente' AND u.estado = 'activo'
        ) THEN RAISE EXCEPTION 'PERMISO_DENEGADO'; END IF;
        DELETE FROM public.pwa_departamento_jefaturas WHERE id_usuario = _target_user;
        DELETE FROM public.pwa_departamento_jefaturas WHERE id_departamento = _target_department;
        INSERT INTO public.pwa_departamento_jefaturas(id_departamento, id_usuario) VALUES (_target_department, _target_user);
      END IF;
      RETURN jsonb_build_object('ok', TRUE);
    END IF;
    IF jsonb_typeof(payload->'id_asignaturas') IS DISTINCT FROM 'array' THEN RAISE EXCEPTION 'ASIGNATURAS_INVALIDAS'; END IF;
    IF jsonb_array_length(payload->'id_asignaturas') > 1000 THEN RAISE EXCEPTION 'ASIGNATURAS_INVALIDAS'; END IF;
    SELECT coalesce(array_agg(DISTINCT item::INTEGER), ARRAY[]::INTEGER[])
      INTO _subject_ids FROM jsonb_array_elements_text(payload->'id_asignaturas') AS items(item);
    SELECT count(*) INTO _count FROM public.asignaturas a WHERE a.id_asignatura = ANY(_subject_ids) AND a.estado = 'activo';
    IF _count <> cardinality(_subject_ids) THEN RAISE EXCEPTION 'ASIGNATURAS_INVALIDAS'; END IF;
    DELETE FROM public.pwa_departamento_asignaturas da
     WHERE da.id_departamento = _target_department AND NOT (da.id_asignatura = ANY(_subject_ids));
    INSERT INTO public.pwa_departamento_asignaturas(id_departamento, id_asignatura)
      SELECT _target_department, item FROM unnest(_subject_ids) AS items(item)
      ON CONFLICT DO NOTHING;
    RETURN jsonb_build_object('ok', TRUE, 'total', cardinality(_subject_ids));
  END IF;

  IF action = 'teachers.list' THEN
    IF NOT _admin AND _department IS NULL THEN RAISE EXCEPTION 'PERMISO_DENEGADO'; END IF;
    SELECT coalesce(jsonb_agg(
      jsonb_build_object(
        'id_docente', u.id_usuario,
        'nombre', u.nombre,
        'correo', u.correo,
        'cedula', u.cedula,
        'estado', u.estado,
        'id_departamento', dd.id_departamento,
        'tipo_docente', (SELECT t.tipo_docente FROM public.pwa_docente_tipo t WHERE t.id_docente = dd.id_docente),
        'componentes', (SELECT coalesce(jsonb_agg(jsonb_build_object('id_asignatura', a.id_asignatura, 'codigo', a.codigo, 'nombre', a.nombre) ORDER BY a.codigo), '[]'::jsonb)
          FROM public.pwa_docente_asignaturas ta
          JOIN public.asignaturas a ON a.id_asignatura = ta.id_asignatura
         WHERE ta.id_departamento = dd.id_departamento AND ta.id_docente = dd.id_docente)
      ) ORDER BY u.nombre
    ), '[]'::jsonb)
      INTO _result
      FROM public.pwa_docente_departamentos dd
      JOIN public.docentes doc ON doc.id_docente = dd.id_docente
      JOIN public.usuarios u ON u.id_usuario = doc.id_docente
     WHERE (_admin OR dd.id_departamento = _department);
    RETURN _result;
  END IF;

  IF action = 'teachers.type' THEN
    _teacher := (payload->>'id_docente')::INTEGER;
    IF NOT _admin AND NOT EXISTS (
      SELECT 1 FROM public.pwa_docente_departamentos dd
       WHERE dd.id_departamento = _department AND dd.id_docente = _teacher
    ) THEN RAISE EXCEPTION 'PERMISO_DENEGADO'; END IF;
    RETURN jsonb_build_object(
      'id_docente', _teacher,
      'tipo_docente', (SELECT t.tipo_docente FROM public.pwa_docente_tipo t WHERE t.id_docente = _teacher)
    );
  END IF;

  IF action IN ('teachers.create', 'teachers.link_existing', 'teachers.set_subjects') THEN
    IF _department IS NULL THEN RAISE EXCEPTION 'PERMISO_DENEGADO'; END IF;
    IF jsonb_typeof(payload->'id_asignaturas') IS DISTINCT FROM 'array' THEN RAISE EXCEPTION 'ASIGNATURAS_INVALIDAS'; END IF;
    IF jsonb_array_length(payload->'id_asignaturas') < 1 OR jsonb_array_length(payload->'id_asignaturas') > 100 THEN RAISE EXCEPTION 'ASIGNATURAS_INVALIDAS'; END IF;
    SELECT coalesce(array_agg(DISTINCT item::INTEGER), ARRAY[]::INTEGER[])
      INTO _subject_ids FROM jsonb_array_elements_text(payload->'id_asignaturas') AS items(item);
    SELECT count(*) INTO _count
      FROM public.pwa_departamento_asignaturas da
      JOIN public.asignaturas a ON a.id_asignatura = da.id_asignatura AND a.estado = 'activo'
     WHERE da.id_departamento = _department AND da.id_asignatura = ANY(_subject_ids);
    IF _count <> cardinality(_subject_ids) THEN RAISE EXCEPTION 'ASIGNATURAS_INVALIDAS'; END IF;

    IF action IN ('teachers.create', 'teachers.link_existing') THEN
      _teacher_type := lower(trim(payload->>'tipo_docente'));
      IF _teacher_type IS NULL OR _teacher_type NOT IN ('planta', 'horario') THEN RAISE EXCEPTION 'TIPO_DOCENTE_INVALIDO'; END IF;
    END IF;

    IF action = 'teachers.link_existing' THEN
      _email := lower(trim(payload->>'correo'));
      _cedula := trim(payload->>'cedula');
      IF _email IS NULL OR char_length(_email) > 100 OR _email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' OR _cedula IS NULL OR char_length(_cedula) NOT BETWEEN 1 AND 20 THEN RAISE EXCEPTION 'DATOS_INVALIDOS'; END IF;
      SELECT u.id_usuario, u.nombre INTO _teacher, _name
        FROM public.usuarios u
       WHERE lower(u.correo) = _email AND u.cedula = _cedula
         AND u.rol = 'docente' AND u.estado = 'activo'
         AND EXISTS (SELECT 1 FROM public.docentes doc WHERE doc.id_docente = u.id_usuario)
       LIMIT 1;
      IF _teacher IS NULL THEN
        IF EXISTS (SELECT 1 FROM public.usuarios u WHERE lower(u.correo) = _email OR u.cedula = _cedula) THEN RAISE EXCEPTION 'DUPLICADO'; END IF;
        RETURN jsonb_build_object('encontrado', FALSE);
      END IF;
      IF EXISTS (SELECT 1 FROM public.pwa_docente_tipo t WHERE t.id_docente = _teacher AND t.tipo_docente <> _teacher_type) THEN RAISE EXCEPTION 'TIPO_DOCENTE_INCOMPATIBLE'; END IF;
      INSERT INTO public.pwa_docente_tipo(id_docente, tipo_docente)
      VALUES (_teacher, _teacher_type) ON CONFLICT (id_docente) DO NOTHING;
      INSERT INTO public.pwa_docente_departamentos(id_departamento, id_docente, registrado_por)
      VALUES (_department, _teacher, _profile.id_usuario)
      ON CONFLICT (id_departamento, id_docente) DO NOTHING;
      DELETE FROM public.pwa_docente_asignaturas ta
       WHERE ta.id_departamento = _department AND ta.id_docente = _teacher AND NOT (ta.id_asignatura = ANY(_subject_ids));
      INSERT INTO public.pwa_docente_asignaturas(id_departamento, id_docente, id_asignatura)
        SELECT _department, _teacher, item FROM unnest(_subject_ids) AS items(item)
        ON CONFLICT DO NOTHING;
      RETURN jsonb_build_object('encontrado', TRUE, 'vinculado', TRUE, 'id_docente', _teacher, 'nombre', _name, 'correo', _email, 'tipo_docente', _teacher_type, 'id_asignaturas', to_jsonb(_subject_ids));
    END IF;

    IF action = 'teachers.create' THEN
      _name := trim(payload->>'nombre');
      _email := lower(trim(payload->>'correo'));
      _cedula := trim(payload->>'cedula');
      IF _name IS NULL OR char_length(_name) NOT BETWEEN 1 AND 100 OR _email IS NULL OR char_length(_email) > 100 OR _email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' OR _cedula IS NULL OR char_length(_cedula) NOT BETWEEN 1 AND 20 THEN RAISE EXCEPTION 'DATOS_INVALIDOS'; END IF;
      IF NOT EXISTS (SELECT 1 FROM auth.users au WHERE lower(au.email) = _email) THEN RAISE EXCEPTION 'AUTH_NO_EXISTE'; END IF;
      IF EXISTS (SELECT 1 FROM public.usuarios u WHERE lower(u.correo) = _email OR u.cedula = _cedula) THEN RAISE EXCEPTION 'DUPLICADO'; END IF;
      -- Supabase Auth es la fuente de autenticacion. Si una instalacion antigua exige
      -- contrasena en usuarios, se guarda un token aleatorio sin utilidad de acceso.
      IF EXISTS (SELECT 1 FROM information_schema.columns c WHERE c.table_schema = 'public' AND c.table_name = 'usuarios' AND c.column_name = 'contrasena' AND c.is_nullable = 'NO' AND c.column_default IS NULL) THEN
        EXECUTE 'INSERT INTO public.usuarios(nombre, correo, cedula, rol, estado, contrasena) VALUES ($1, $2, $3, $4, $5, gen_random_uuid()::text) RETURNING id_usuario'
          INTO _teacher USING _name, _email, _cedula, 'docente', 'activo';
      ELSE
        INSERT INTO public.usuarios(nombre, correo, cedula, rol, estado)
        VALUES (_name, _email, _cedula, 'docente', 'activo') RETURNING id_usuario INTO _teacher;
      END IF;
      INSERT INTO public.docentes(id_docente) VALUES (_teacher) ON CONFLICT (id_docente) DO NOTHING;
      INSERT INTO public.pwa_docente_tipo(id_docente, tipo_docente) VALUES (_teacher, _teacher_type);
      INSERT INTO public.pwa_docente_departamentos(id_departamento, id_docente, registrado_por)
      VALUES (_department, _teacher, _profile.id_usuario);
      INSERT INTO public.pwa_docente_asignaturas(id_departamento, id_docente, id_asignatura)
      SELECT _department, _teacher, item FROM unnest(_subject_ids) AS items(item);
      RETURN jsonb_build_object('ok', TRUE, 'id_docente', _teacher, 'id_asignaturas', to_jsonb(_subject_ids));
    END IF;

    _teacher := (payload->>'id_docente')::INTEGER;
    IF NOT EXISTS (SELECT 1 FROM public.pwa_docente_departamentos dd WHERE dd.id_departamento = _department AND dd.id_docente = _teacher) THEN RAISE EXCEPTION 'PERMISO_DENEGADO'; END IF;
    DELETE FROM public.pwa_docente_asignaturas ta
     WHERE ta.id_departamento = _department AND ta.id_docente = _teacher AND NOT (ta.id_asignatura = ANY(_subject_ids));
    INSERT INTO public.pwa_docente_asignaturas(id_departamento, id_docente, id_asignatura)
      SELECT _department, _teacher, item FROM unnest(_subject_ids) AS items(item)
      ON CONFLICT DO NOTHING;
    RETURN jsonb_build_object('ok', TRUE, 'id_docente', _teacher, 'id_asignaturas', to_jsonb(_subject_ids));
  END IF;

  RAISE EXCEPTION 'ACCION_NO_RECONOCIDA';
END;
$$;

REVOKE ALL ON FUNCTION public.pwa_jefatura_academica(TEXT, JSONB) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.pwa_jefatura_academica(TEXT, JSONB) TO authenticated;

COMMIT;
