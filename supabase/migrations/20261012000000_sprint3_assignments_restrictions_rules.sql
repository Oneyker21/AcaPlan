CREATE OR REPLACE FUNCTION public.save_planning_rules(p_period_id INTEGER, p_rules JSONB)
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    new_version INTEGER;
    saturday_transfer BOOLEAN;
BEGIN
    IF NOT public.is_active_admin() AND NOT public.is_active_planner() THEN
        RAISE EXCEPTION 'Only planning can change institutional rules.' USING ERRCODE = '42501';
    END IF;
    IF p_rules IS NULL OR jsonb_typeof(p_rules) <> 'object' THEN
        RAISE EXCEPTION 'Rules must be a JSON object.' USING ERRCODE = '22023';
    END IF;
    IF EXISTS (
        SELECT 1 FROM jsonb_object_keys(p_rules) AS rule_key(key)
        WHERE rule_key.key NOT IN ('traslado_sabado_libre', 'peso_distribucion_equilibrada', 'peso_minimizar_huecos')
    ) THEN
        RAISE EXCEPTION 'The rules contain unsupported fields.' USING ERRCODE = '22023';
    END IF;
    IF COALESCE(p_rules ? 'traslado_sabado_libre', FALSE)
       AND jsonb_typeof(p_rules->'traslado_sabado_libre') <> 'boolean' THEN
        RAISE EXCEPTION 'Saturday transfer must be true or false.' USING ERRCODE = '22023';
    END IF;
    IF EXISTS (
        SELECT 1 FROM jsonb_each(p_rules) AS entry(key, value)
        WHERE entry.key IN ('peso_distribucion_equilibrada', 'peso_minimizar_huecos')
          AND (jsonb_typeof(entry.value) <> 'number' OR (entry.value #>> '{}')::INTEGER NOT BETWEEN 0 AND 100)
    ) THEN
        RAISE EXCEPTION 'Preference weights must be whole numbers from 0 to 100.' USING ERRCODE = '22023';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.periodos WHERE id_periodo = p_period_id) THEN
        RAISE EXCEPTION 'The selected period does not exist.' USING ERRCODE = '23503';
    END IF;
    saturday_transfer := COALESCE((p_rules->>'traslado_sabado_libre')::BOOLEAN, FALSE);
    IF saturday_transfer AND NOT (
        EXISTS (
            SELECT 1 FROM public.secciones
            WHERE id_periodo = p_period_id AND sede ILIKE '%CUR%'
        ) AND EXISTS (
            SELECT 1 FROM public.secciones
            WHERE id_periodo = p_period_id AND sede ILIKE '%instituto%'
        )
    ) THEN
        RAISE EXCEPTION 'Saturday transfer applies only when the period has classes at both CUR and Instituto sites.' USING ERRCODE = '23514';
    END IF;
    PERFORM pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext('acaplan_rules_' || p_period_id::TEXT));
    SELECT COALESCE(MAX(numero_version), 0) + 1 INTO new_version
    FROM public.versiones_reglas_planificacion WHERE id_periodo = p_period_id;
    INSERT INTO public.versiones_reglas_planificacion (id_periodo, numero_version, reglas, creada_por)
    VALUES (p_period_id, new_version, p_rules, public.current_app_user_id());
    RETURN new_version;
END;
$$;
REVOKE ALL ON FUNCTION public.save_planning_rules(INTEGER, JSONB) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.save_planning_rules(INTEGER, JSONB) TO authenticated;

CREATE OR REPLACE FUNCTION public.save_academic_assignment_component(
    p_section_id INTEGER,
    p_subject_id INTEGER,
    p_component JSONB
)
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    section_career_id INTEGER;
    section_period_id INTEGER;
    section_year INTEGER;
    section_modality TEXT;
    section_shift TEXT;
    session_type TEXT;
    session_count INTEGER;
    duration_minutes INTEGER;
    requires_specialized BOOLEAN;
    need_note TEXT;
    teacher_ids INTEGER[];
    resource_ids INTEGER[];
    assignment_id INTEGER;
    component_id INTEGER;
BEGIN
    SELECT id_carrera, id_periodo, ano_estudio, modalidad, turno
    INTO section_career_id, section_period_id, section_year, section_modality, section_shift
    FROM public.secciones WHERE id_seccion = p_section_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'The selected group does not exist.' USING ERRCODE = '23503';
    END IF;
    IF NOT public.can_manage_career(section_career_id) THEN
        RAISE EXCEPTION 'You cannot manage this career.' USING ERRCODE = '42501';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM public.seccion_asignatura
        WHERE id_seccion = p_section_id AND id_asignatura = p_subject_id
    ) OR NOT EXISTS (
        SELECT 1 FROM public.asignaturas
        WHERE id_asignatura = p_subject_id AND id_carrera = section_career_id
          AND ano_estudio = section_year AND estado = 'activo'
    ) THEN
        RAISE EXCEPTION 'The subject must be active and linked to this group career and study year.' USING ERRCODE = '23514';
    END IF;
    IF p_component IS NULL OR jsonb_typeof(p_component) <> 'object' THEN
        RAISE EXCEPTION 'The class component is invalid.' USING ERRCODE = '22023';
    END IF;
    session_type := p_component->>'tipo_sesion';
    IF session_type NOT IN ('teorica', 'practica') THEN
        RAISE EXCEPTION 'Class type must be theoretical or practical.' USING ERRCODE = '22023';
    END IF;
    IF COALESCE(p_component->>'sesiones_semana', '') !~ '^[0-9]+$'
       OR COALESCE(p_component->>'duracion_minutos', '') !~ '^[0-9]+$' THEN
        RAISE EXCEPTION 'Weekly sessions and session duration must be whole numbers.' USING ERRCODE = '22023';
    END IF;
    session_count := (p_component->>'sesiones_semana')::INTEGER;
    duration_minutes := (p_component->>'duracion_minutos')::INTEGER;
    IF session_count NOT BETWEEN 1 AND 20 OR duration_minutes NOT BETWEEN 1 AND 480 THEN
        RAISE EXCEPTION 'Weekly sessions must be 1–20 and duration must be 1–480 minutes.' USING ERRCODE = '22023';
    END IF;
    requires_specialized := COALESCE((p_component->>'requiere_espacio_especializado')::BOOLEAN, FALSE);
    need_note := btrim(COALESCE(p_component->>'observacion_espacio', ''));
    IF length(need_note) > 300 OR (requires_specialized AND need_note = '') THEN
        RAISE EXCEPTION 'Describe the required specialized space in at most 300 characters.' USING ERRCODE = '22023';
    END IF;
    SELECT COALESCE(array_agg(DISTINCT value::INTEGER), ARRAY[]::INTEGER[])
    INTO teacher_ids
    FROM jsonb_array_elements_text(COALESCE(p_component->'docentes', '[]'::JSONB)) AS teacher(value);
    IF COALESCE(pg_catalog.cardinality(teacher_ids), 0) = 0 THEN
        RAISE EXCEPTION 'Select at least one official active teacher.' USING ERRCODE = '23514';
    END IF;
    IF EXISTS (
        SELECT 1 FROM pg_catalog.unnest(teacher_ids) AS selected(id_docente)
        WHERE NOT EXISTS (
            SELECT 1 FROM public.docentes AS docente
            JOIN public.usuarios AS usuario ON usuario.id_usuario = docente.id_docente
            WHERE docente.id_docente = selected.id_docente
              AND usuario.rol = 'docente' AND usuario.estado = 'activo'
        )
    ) THEN
        RAISE EXCEPTION 'Only active official teachers can be assigned.' USING ERRCODE = '23514';
    END IF;
    SELECT COALESCE(array_agg(DISTINCT value::INTEGER), ARRAY[]::INTEGER[])
    INTO resource_ids
    FROM jsonb_array_elements_text(COALESCE(p_component->'recursos', '[]'::JSONB)) AS resource(value);
    IF EXISTS (
        SELECT 1 FROM pg_catalog.unnest(resource_ids) AS selected(id_recurso)
        WHERE NOT EXISTS (SELECT 1 FROM public.recursos WHERE id_recurso = selected.id_recurso)
    ) THEN
        RAISE EXCEPTION 'One or more selected equipment/resources are not in the catalog.' USING ERRCODE = '23503';
    END IF;
    INSERT INTO public.asignaciones_academicas (id_periodo, id_seccion, id_asignatura, observacion_espacio, creado_por)
    VALUES (section_period_id, p_section_id, p_subject_id, need_note, public.current_app_user_id())
    ON CONFLICT (id_seccion, id_asignatura)
    DO UPDATE SET observacion_espacio = EXCLUDED.observacion_espacio,
                  fecha_actualizacion = pg_catalog.now()
    RETURNING id_asignacion_academica INTO assignment_id;

    INSERT INTO public.asignacion_componentes (
        id_asignacion_academica, tipo_sesion, sesiones_semana, duracion_minutos,
        requiere_espacio_especializado, observacion_espacio
    ) VALUES (
        assignment_id, session_type, session_count, duration_minutes,
        requires_specialized, need_note
    )
    ON CONFLICT (id_asignacion_academica, tipo_sesion)
    DO UPDATE SET sesiones_semana = EXCLUDED.sesiones_semana,
                  duracion_minutos = EXCLUDED.duracion_minutos,
                  requiere_espacio_especializado = EXCLUDED.requiere_espacio_especializado,
                  observacion_espacio = EXCLUDED.observacion_espacio
    RETURNING id_componente INTO component_id;

    DELETE FROM public.asignacion_componente_docente WHERE id_componente = component_id;
    INSERT INTO public.asignacion_componente_docente (id_componente, id_docente)
    SELECT component_id, selected.id_docente FROM pg_catalog.unnest(teacher_ids) AS selected(id_docente);
    DELETE FROM public.asignacion_componente_recurso WHERE id_componente = component_id;
    INSERT INTO public.asignacion_componente_recurso (id_componente, id_recurso)
    SELECT component_id, selected.id_recurso FROM pg_catalog.unnest(resource_ids) AS selected(id_recurso);
    RETURN assignment_id;
END;
$$;
REVOKE ALL ON FUNCTION public.save_academic_assignment_component(INTEGER, INTEGER, JSONB) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.save_academic_assignment_component(INTEGER, INTEGER, JSONB) TO authenticated;

-- A file import uses the same validation and save path for every row. Any
-- failure rolls the entire transaction back and the message carries sheet/row.
CREATE OR REPLACE FUNCTION public.import_academic_assignment_batch(p_rows JSONB)
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    input_row JSONB;
    imported_count INTEGER := 0;
    row_label TEXT;
    row_key TEXT;
    seen_rows TEXT[] := ARRAY[]::TEXT[];
BEGIN
    IF p_rows IS NULL OR jsonb_typeof(p_rows) <> 'array'
       OR jsonb_array_length(p_rows) = 0 OR jsonb_array_length(p_rows) > 2000 THEN
        RAISE EXCEPTION 'Select between 1 and 2,000 valid assignment rows.' USING ERRCODE = '22023';
    END IF;
    FOR input_row IN SELECT value FROM jsonb_array_elements(p_rows) AS rows(value) LOOP
        row_label := COALESCE(NULLIF(btrim(input_row->>'sheet'), ''), 'Hoja') || ', fila ' || COALESCE(input_row->>'row', '?');
        row_key := concat_ws(':', input_row->>'section_id', input_row->>'subject_id', input_row->>'tipo_sesion');
        IF row_key = ANY(seen_rows) THEN
            RAISE EXCEPTION '%: repeated group, subject, and class type.', row_label USING ERRCODE = '23505';
        END IF;
        seen_rows := array_append(seen_rows, row_key);
        BEGIN
            PERFORM public.save_academic_assignment_component(
                (input_row->>'section_id')::INTEGER,
                (input_row->>'subject_id')::INTEGER,
                jsonb_build_object(
                    'tipo_sesion', input_row->>'tipo_sesion',
                    'sesiones_semana', input_row->>'sesiones_semana',
                    'duracion_minutos', input_row->>'duracion_minutos',
                    'requiere_espacio_especializado', COALESCE((input_row->>'requiere_espacio_especializado')::BOOLEAN, FALSE),
                    'observacion_espacio', COALESCE(input_row->>'observacion_espacio', ''),
                    'docentes', COALESCE(input_row->'docentes', '[]'::JSONB),
                    'recursos', COALESCE(input_row->'recursos', '[]'::JSONB)
                )
            );
        EXCEPTION WHEN OTHERS THEN
            RAISE EXCEPTION '%: %', row_label, SQLERRM USING ERRCODE = SQLSTATE;
        END;
        imported_count := imported_count + 1;
    END LOOP;
    RETURN imported_count;
END;
$$;
REVOKE ALL ON FUNCTION public.import_academic_assignment_batch(JSONB) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.import_academic_assignment_batch(JSONB) TO authenticated;

COMMIT;
