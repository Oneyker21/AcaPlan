CREATE OR REPLACE FUNCTION public.is_active_department_head()
RETURNS BOOLEAN
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT EXISTS (
        SELECT 1 FROM public.usuarios AS usuario
        WHERE usuario.auth_user_id = auth.uid()
          AND usuario.estado = 'activo'
          AND usuario.rol = 'jefatura'
    )
$$;

CREATE OR REPLACE FUNCTION public.can_view_career(target_career_id INTEGER)
RETURNS BOOLEAN
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT public.can_manage_career(target_career_id)
        OR (
            public.is_active_department_head()
            AND EXISTS (
                SELECT 1 FROM public.usuario_carrera AS assigned
                WHERE assigned.id_usuario = public.current_app_user_id()
                  AND assigned.id_carrera = target_career_id
            )
        )
$$;

