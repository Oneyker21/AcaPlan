CREATE OR REPLACE FUNCTION public.validate_planning_restriction()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    requested_site TEXT;
    selected_group_ids INTEGER[];
BEGIN
    IF NEW.tipo_afectado = 'docente' AND NOT EXISTS (
        SELECT 1 FROM public.docentes AS docente
        JOIN public.usuarios AS usuario ON usuario.id_usuario = docente.id_docente
        WHERE docente.id_docente = NEW.id_afectado
          AND usuario.rol = 'docente' AND usuario.estado = 'activo'
    ) THEN
        RAISE EXCEPTION 'The affected teacher must be an active official teacher.' USING ERRCODE = '23503';
    END IF;
    IF NEW.tipo_afectado = 'asignatura' AND NOT EXISTS (
        SELECT 1 FROM public.asignaturas
        WHERE id_asignatura = NEW.id_afectado AND id_carrera = NEW.id_carrera
    ) THEN
        RAISE EXCEPTION 'The affected subject must belong to the selected career.' USING ERRCODE = '23514';
    END IF;
    IF NEW.tipo_afectado = 'grupo' AND NOT EXISTS (
        SELECT 1 FROM public.secciones
        WHERE id_seccion = NEW.id_afectado
          AND id_carrera = NEW.id_carrera
          AND id_periodo = NEW.id_periodo
    ) THEN
        RAISE EXCEPTION 'The affected group must belong to the selected career and period.' USING ERRCODE = '23514';
    END IF;
    IF NEW.tipo_afectado = 'sede' THEN
        requested_site := btrim(COALESCE(NEW.parametros->>'sede', ''));
        IF requested_site = '' OR length(requested_site) > 150 THEN
            RAISE EXCEPTION 'A site restriction needs the affected site name.' USING ERRCODE = '22023';
        END IF;
    END IF;
    IF NEW.condicion = 'juntas' THEN
        IF jsonb_typeof(NEW.parametros->'grupos') IS DISTINCT FROM 'array' THEN
            RAISE EXCEPTION 'A classes-together restriction needs at least two group IDs.' USING ERRCODE = '22023';
        END IF;
        IF jsonb_array_length(NEW.parametros->'grupos') < 2 THEN
            RAISE EXCEPTION 'A classes-together restriction needs at least two group IDs.' USING ERRCODE = '22023';
        END IF;
        IF EXISTS (
            SELECT 1
            FROM jsonb_array_elements_text(NEW.parametros->'grupos') AS selected(value)
            WHERE selected.value !~ '^[0-9]+$'
        ) THEN
            RAISE EXCEPTION 'A classes-together restriction needs valid group IDs.' USING ERRCODE = '22023';
        END IF;
        SELECT COALESCE(array_agg(DISTINCT selected.value::INTEGER), ARRAY[]::INTEGER[])
        INTO selected_group_ids
        FROM jsonb_array_elements_text(NEW.parametros->'grupos') AS selected(value);
        IF pg_catalog.cardinality(selected_group_ids) < 2 OR EXISTS (
            SELECT 1
            FROM pg_catalog.unnest(selected_group_ids) AS requested(id_seccion)
            WHERE NOT EXISTS (
                SELECT 1 FROM public.secciones AS seccion
                WHERE seccion.id_seccion = requested.id_seccion
                  AND seccion.id_periodo = NEW.id_periodo
                  AND seccion.id_carrera = NEW.id_carrera
            )
        ) THEN
            RAISE EXCEPTION 'All classes-together groups must belong to the selected career and period.' USING ERRCODE = '23514';
        END IF;
    END IF;
    IF TG_OP = 'UPDATE' THEN
        IF NEW.creada_por IS DISTINCT FROM OLD.creada_por THEN
            RAISE EXCEPTION 'The responsible account cannot be changed.' USING ERRCODE = '23514';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS restricciones_validate_scope ON public.restricciones_planificacion;
CREATE TRIGGER restricciones_validate_scope
    BEFORE INSERT OR UPDATE ON public.restricciones_planificacion
    FOR EACH ROW EXECUTE FUNCTION public.validate_planning_restriction();

CREATE OR REPLACE FUNCTION public.preview_restriction_impact(
    p_period_id INTEGER,
    p_career_id INTEGER,
    p_affected_type TEXT,
    p_affected_id INTEGER,
    p_condition TEXT,
    p_day public.dias_semana,
    p_start TIME,
    p_end TIME,
    p_parameters JSONB DEFAULT '{}'::JSONB
)
RETURNS TABLE(group_code TEXT, subject_name TEXT, teacher_name TEXT, day_name TEXT, time_range TEXT)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    together_group_ids INTEGER[];
BEGIN
    IF NOT public.can_view_career(p_career_id) THEN
        RAISE EXCEPTION 'You cannot view restrictions for this career.' USING ERRCODE = '42501';
    END IF;
    IF (p_start IS NULL) <> (p_end IS NULL) OR (p_start IS NOT NULL AND p_start >= p_end) THEN
        RAISE EXCEPTION 'Enter a valid start and end time.' USING ERRCODE = '22023';
    END IF;
    IF p_condition = 'juntas' THEN
        IF jsonb_typeof(p_parameters->'grupos') IS DISTINCT FROM 'array' THEN
            RAISE EXCEPTION 'Select at least two groups for a classes-together restriction.' USING ERRCODE = '22023';
        END IF;
        SELECT COALESCE(array_agg(DISTINCT value::INTEGER), ARRAY[]::INTEGER[])
        INTO together_group_ids
        FROM jsonb_array_elements_text(p_parameters->'grupos') AS selected(value);
        IF pg_catalog.cardinality(together_group_ids) < 2 THEN
            RAISE EXCEPTION 'Select at least two groups for a classes-together restriction.' USING ERRCODE = '22023';
        END IF;
    END IF;
    RETURN QUERY
    SELECT seccion.codigo::TEXT,
           asignatura.nombre::TEXT,
           usuario.nombre::TEXT,
           bloque.dia::TEXT,
           pg_catalog.to_char(bloque.hora_inicio, 'HH24:MI') || '–' || pg_catalog.to_char(bloque.hora_fin, 'HH24:MI')
    FROM public.horarios AS horario
    JOIN public.secciones AS seccion ON seccion.id_seccion = horario.id_seccion
    JOIN public.asignaturas AS asignatura ON asignatura.id_asignatura = horario.id_asignatura
    JOIN public.usuarios AS usuario ON usuario.id_usuario = horario.id_docente
    JOIN public.bloques_clase AS bloque ON bloque.id_bloque = horario.id_bloque
    WHERE bloque.id_periodo = p_period_id
      AND seccion.id_carrera = p_career_id
      AND (p_day IS NULL OR bloque.dia = p_day)
      AND (p_start IS NULL OR (p_start < bloque.hora_fin AND p_end > bloque.hora_inicio))
      AND CASE p_affected_type
          WHEN 'docente' THEN horario.id_docente = p_affected_id
          WHEN 'asignatura' THEN horario.id_asignatura = p_affected_id
          WHEN 'grupo' THEN horario.id_seccion = p_affected_id
          WHEN 'sede' THEN seccion.sede = COALESCE(p_parameters->>'sede', '')
          WHEN 'carrera' THEN TRUE
          ELSE FALSE
      END
      AND (p_condition <> 'juntas' OR horario.id_seccion = ANY(together_group_ids))
    ORDER BY bloque.dia, bloque.hora_inicio, seccion.codigo;
END;
$$;
REVOKE ALL ON FUNCTION public.preview_restriction_impact(INTEGER, INTEGER, TEXT, INTEGER, TEXT, public.dias_semana, TIME, TIME, JSONB) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.preview_restriction_impact(INTEGER, INTEGER, TEXT, INTEGER, TEXT, public.dias_semana, TIME, TIME, JSONB) TO authenticated;

