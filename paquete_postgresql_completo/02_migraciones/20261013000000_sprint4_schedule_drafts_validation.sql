CREATE OR REPLACE FUNCTION public.can_view_schedule_version(p_version_id INTEGER)
RETURNS BOOLEAN
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT public.is_active_admin() OR public.is_active_planner() OR EXISTS (
        SELECT 1
        FROM public.versiones_horario AS version
        JOIN public.usuarios AS usuario ON usuario.id_usuario = public.current_app_user_id()
        WHERE version.id_version_horario = p_version_id
          AND usuario.estado = 'activo'
          AND (
              version.estado = 'publicado'
              OR (version.estado = 'compartido' AND usuario.rol = ANY(version.roles_compartidos))
          )
    )
$$;
