CREATE OR REPLACE FUNCTION public.validate_schedule_version(p_version_id INTEGER)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    target_period INTEGER;
    latest_rules_version INTEGER;
    issue JSONB;
    issues JSONB := '[]'::JSONB;
    error_count INTEGER := 0;
    warning_count INTEGER := 0;
    validation_state TEXT;
    restriction_row RECORD;
    group_ids INTEGER[];
    matching_slot_count INTEGER;
BEGIN
    IF NOT public.is_active_admin() AND NOT public.is_active_planner() THEN
        RAISE EXCEPTION 'Only planning can validate schedule drafts.' USING ERRCODE = '42501';
    END IF;
    PERFORM pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext('acaplan_version_' || p_version_id::TEXT));
    SELECT id_periodo INTO target_period FROM public.versiones_horario
    WHERE id_version_horario = p_version_id AND estado IN ('borrador', 'compartido', 'aprobado') FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'The selected schedule version is not available for validation.' USING ERRCODE = '23514'; END IF;
    SELECT id_version_reglas INTO latest_rules_version
    FROM public.versiones_reglas_planificacion
    WHERE id_periodo = target_period ORDER BY numero_version DESC LIMIT 1;
    UPDATE public.versiones_horario SET reglas_version_id = latest_rules_version
    WHERE id_version_horario = p_version_id;

    -- Every weekly component must be represented by the correct number of sessions.
    FOR issue IN
        SELECT jsonb_build_object(
            'code', 'clase_sin_asignacion_oficial', 'severity', 'error',
            'message', 'La clase no está vinculada a una asignación académica oficial del período.',
            'group', seccion.codigo, 'subject', asignatura.nombre
        )
        FROM public.horarios AS horario
        JOIN public.secciones AS seccion ON seccion.id_seccion = horario.id_seccion
        JOIN public.asignaturas AS asignatura ON asignatura.id_asignatura = horario.id_asignatura
        WHERE horario.id_version_horario = p_version_id AND horario.id_componente IS NULL
        ORDER BY seccion.codigo, asignatura.nombre
    LOOP issues := issues || jsonb_build_array(issue); END LOOP;

    FOR issue IN
        SELECT jsonb_build_object(
            'code', 'sesiones_incompletas', 'severity', 'error',
            'message', 'La asignación oficial no tiene todas sus sesiones semanales colocadas.',
            'group', seccion.codigo, 'subject', asignatura.nombre,
            'scheduled', COUNT(horario.id_horario), 'expected', componente.sesiones_semana
        )
        FROM public.asignacion_componentes AS componente
        JOIN public.asignaciones_academicas AS asignacion USING (id_asignacion_academica)
        JOIN public.secciones AS seccion ON seccion.id_seccion = asignacion.id_seccion
        JOIN public.asignaturas AS asignatura ON asignatura.id_asignatura = asignacion.id_asignatura
        LEFT JOIN public.horarios AS horario
          ON horario.id_version_horario = p_version_id AND horario.id_componente = componente.id_componente
        WHERE asignacion.id_periodo = target_period
        GROUP BY componente.id_componente, componente.sesiones_semana, seccion.codigo, asignatura.nombre
        HAVING COUNT(horario.id_horario) <> componente.sesiones_semana
        ORDER BY seccion.codigo, asignatura.nombre
    LOOP issues := issues || jsonb_build_array(issue); END LOOP;

    FOR issue IN
        SELECT jsonb_build_object(
            'code', 'cuadricula_obsoleta', 'severity', 'error',
            'message', 'La sesión conserva una hora de una cuadrícula anterior. Vuelva a seleccionar un bloque vigente para esta clase.',
            'group', seccion.codigo, 'subject', asignatura.nombre,
            'saved_day', horario.dia_snapshot, 'current_day', bloque.dia,
            'saved_start', horario.hora_inicio_snapshot, 'current_start', bloque.hora_inicio,
            'saved_end', horario.hora_fin_snapshot, 'current_end', bloque.hora_fin
        )
        FROM public.horarios AS horario
        JOIN public.bloques_clase AS bloque ON bloque.id_bloque = horario.id_bloque
        JOIN public.secciones AS seccion ON seccion.id_seccion = horario.id_seccion
        JOIN public.asignaturas AS asignatura ON asignatura.id_asignatura = horario.id_asignatura
        WHERE horario.id_version_horario = p_version_id
          AND (horario.dia_snapshot IS DISTINCT FROM bloque.dia
            OR horario.hora_inicio_snapshot IS DISTINCT FROM bloque.hora_inicio
            OR horario.hora_fin_snapshot IS DISTINCT FROM bloque.hora_fin)
        ORDER BY seccion.codigo, asignatura.nombre
    LOOP issues := issues || jsonb_build_array(issue); END LOOP;

    FOR issue IN
        SELECT jsonb_build_object(
            'code', 'docente_faltante', 'severity', 'error',
            'message', 'La clase no incluye a todos los docentes indicados en la asignación oficial.',
            'group', seccion.codigo, 'subject', asignatura.nombre, 'teacher', usuario.nombre
        )
        FROM public.horarios AS horario
        JOIN public.asignacion_componente_docente AS requerido ON requerido.id_componente = horario.id_componente
        JOIN public.usuarios AS usuario ON usuario.id_usuario = requerido.id_docente
        JOIN public.secciones AS seccion ON seccion.id_seccion = horario.id_seccion
        JOIN public.asignaturas AS asignatura ON asignatura.id_asignatura = horario.id_asignatura
        WHERE horario.id_version_horario = p_version_id
          AND NOT EXISTS (
              SELECT 1 FROM public.horario_docente AS participante
              WHERE participante.id_horario = horario.id_horario AND participante.id_docente = requerido.id_docente
          )
        ORDER BY seccion.codigo, asignatura.nombre, usuario.nombre
    LOOP issues := issues || jsonb_build_array(issue); END LOOP;

    -- Conflicts are isolated to one version and include every participating teacher.
    FOR issue IN
        SELECT jsonb_build_object(
            'code', 'cruce_de_recursos', 'severity', 'error',
            'message', CASE
                WHEN left_class.id_seccion = right_class.id_seccion THEN 'El grupo tiene dos clases que se cruzan.'
                WHEN left_class.id_aula = right_class.id_aula THEN 'El mismo espacio está asignado a dos clases que se cruzan.'
                ELSE 'Un docente participa en dos clases que se cruzan.'
            END,
            'classes', jsonb_build_array(
                jsonb_build_object('group', left_section.codigo, 'subject', left_subject.nombre, 'start', COALESCE(left_class.hora_inicio_snapshot, left_block.hora_inicio), 'end', COALESCE(left_class.hora_fin_snapshot, left_block.hora_fin)),
                jsonb_build_object('group', right_section.codigo, 'subject', right_subject.nombre, 'start', COALESCE(right_class.hora_inicio_snapshot, right_block.hora_inicio), 'end', COALESCE(right_class.hora_fin_snapshot, right_block.hora_fin))
            ),
            'resource', CASE WHEN left_class.id_seccion = right_class.id_seccion THEN 'grupo' WHEN left_class.id_aula = right_class.id_aula THEN left_room.codigo ELSE 'docente' END
        )
        FROM public.horarios AS left_class
        JOIN public.bloques_clase AS left_block ON left_block.id_bloque = left_class.id_bloque
        JOIN public.secciones AS left_section ON left_section.id_seccion = left_class.id_seccion
        JOIN public.asignaturas AS left_subject ON left_subject.id_asignatura = left_class.id_asignatura
        JOIN public.aulas AS left_room ON left_room.id_aula = left_class.id_aula
        JOIN public.horarios AS right_class
          ON right_class.id_version_horario = left_class.id_version_horario
         AND right_class.id_horario > left_class.id_horario
        JOIN public.bloques_clase AS right_block ON right_block.id_bloque = right_class.id_bloque
        JOIN public.secciones AS right_section ON right_section.id_seccion = right_class.id_seccion
        JOIN public.asignaturas AS right_subject ON right_subject.id_asignatura = right_class.id_asignatura
        WHERE left_class.id_version_horario = p_version_id
          AND COALESCE(right_class.dia_snapshot, right_block.dia) = COALESCE(left_class.dia_snapshot, left_block.dia)
          AND COALESCE(left_class.hora_inicio_snapshot, left_block.hora_inicio) < COALESCE(right_class.hora_fin_snapshot, right_block.hora_fin)
          AND COALESCE(left_class.hora_fin_snapshot, left_block.hora_fin) > COALESCE(right_class.hora_inicio_snapshot, right_block.hora_inicio)
          AND (
              left_class.id_seccion = right_class.id_seccion
              OR left_class.id_aula = right_class.id_aula
              OR EXISTS (
                  SELECT 1
                  FROM (
                      SELECT left_class.id_docente AS id_docente
                      UNION SELECT participant.id_docente FROM public.horario_docente AS participant WHERE participant.id_horario = left_class.id_horario
                  ) AS left_teacher
                  JOIN (
                      SELECT right_class.id_docente AS id_docente
                      UNION SELECT participant.id_docente FROM public.horario_docente AS participant WHERE participant.id_horario = right_class.id_horario
                  ) AS right_teacher USING (id_docente)
              )
          )
        ORDER BY COALESCE(left_class.dia_snapshot, left_block.dia), COALESCE(left_class.hora_inicio_snapshot, left_block.hora_inicio)
    LOOP issues := issues || jsonb_build_array(issue); END LOOP;

    FOR issue IN
        SELECT jsonb_build_object(
            'code', 'espacio_inactivo', 'severity', 'error',
            'message', 'El espacio dejó de estar activo en el inventario oficial.',
            'group', seccion.codigo, 'subject', asignatura.nombre, 'room', aula.codigo
        )
        FROM public.horarios AS horario
        JOIN public.secciones AS seccion ON seccion.id_seccion = horario.id_seccion
        JOIN public.asignaturas AS asignatura ON asignatura.id_asignatura = horario.id_asignatura
        JOIN public.aulas AS aula ON aula.id_aula = horario.id_aula
        WHERE horario.id_version_horario = p_version_id AND aula.estado <> 'activo'
        ORDER BY seccion.codigo, aula.codigo
    LOOP issues := issues || jsonb_build_array(issue); END LOOP;

    FOR issue IN
        SELECT jsonb_build_object(
            'code', 'cuadricula_incompatible', 'severity', 'error',
            'message', 'El bloque ya no corresponde a la modalidad, turno o días habilitados para el grupo.',
            'group', seccion.codigo, 'subject', asignatura.nombre,
            'day', bloque.dia, 'start', bloque.hora_inicio, 'end', bloque.hora_fin
        )
        FROM public.horarios AS horario
        JOIN public.bloques_clase AS bloque ON bloque.id_bloque = horario.id_bloque
        JOIN public.secciones AS seccion ON seccion.id_seccion = horario.id_seccion
        JOIN public.asignaturas AS asignatura ON asignatura.id_asignatura = horario.id_asignatura
        WHERE horario.id_version_horario = p_version_id
          AND (bloque.id_periodo <> target_period
            OR bloque.modalidad <> seccion.modalidad
            OR bloque.turno <> seccion.turno
            OR NOT EXISTS (
                SELECT 1 FROM public.dias_habilitados_periodo AS habilitado
                WHERE habilitado.id_periodo = target_period
                  AND habilitado.modalidad = seccion.modalidad
                  AND habilitado.turno = seccion.turno
                  AND habilitado.dia = bloque.dia
            ))
        ORDER BY seccion.codigo, asignatura.nombre
    LOOP issues := issues || jsonb_build_array(issue); END LOOP;

    FOR issue IN
        SELECT jsonb_build_object(
            'code', 'docente_no_asignado', 'severity', 'error',
            'message', 'La clase incluye un docente que no pertenece a su asignación académica oficial.',
            'group', seccion.codigo, 'subject', asignatura.nombre, 'teacher', usuario.nombre
        )
        FROM public.horarios AS horario
        JOIN public.horario_docente AS participante ON participante.id_horario = horario.id_horario
        JOIN public.usuarios AS usuario ON usuario.id_usuario = participante.id_docente
        JOIN public.secciones AS seccion ON seccion.id_seccion = horario.id_seccion
        JOIN public.asignaturas AS asignatura ON asignatura.id_asignatura = horario.id_asignatura
        WHERE horario.id_version_horario = p_version_id
          AND horario.id_componente IS NOT NULL
          AND NOT EXISTS (
              SELECT 1 FROM public.asignacion_componente_docente AS asignado
              WHERE asignado.id_componente = horario.id_componente
                AND asignado.id_docente = participante.id_docente
          )
        ORDER BY seccion.codigo, asignatura.nombre, usuario.nombre
    LOOP issues := issues || jsonb_build_array(issue); END LOOP;

    FOR issue IN
        SELECT jsonb_build_object(
            'code', 'capacidad_insuficiente', 'severity', 'error',
            'message', 'La capacidad del espacio es menor que la cantidad registrada para el grupo.',
            'group', seccion.codigo, 'room', aula.codigo, 'capacity', aula.capacidad, 'students', seccion.cantidad_estudiantes
        )
        FROM public.horarios AS horario
        JOIN public.secciones AS seccion ON seccion.id_seccion = horario.id_seccion
        JOIN public.aulas AS aula ON aula.id_aula = horario.id_aula
        WHERE horario.id_version_horario = p_version_id AND aula.capacidad < seccion.cantidad_estudiantes
        ORDER BY seccion.codigo, aula.codigo
    LOOP issues := issues || jsonb_build_array(issue); END LOOP;

    FOR issue IN
        WITH required_resources AS (
            SELECT horario.id_horario, horario.id_aula, componente_recurso.id_recurso
            FROM public.horarios AS horario
            JOIN public.asignacion_componente_recurso AS componente_recurso ON componente_recurso.id_componente = horario.id_componente
            WHERE horario.id_version_horario = p_version_id
            UNION
            SELECT horario.id_horario, horario.id_aula, asignatura_recurso.id_recurso
            FROM public.horarios AS horario
            JOIN public.asignatura_recurso AS asignatura_recurso ON asignatura_recurso.id_asignatura = horario.id_asignatura
            WHERE horario.id_version_horario = p_version_id
        )
        SELECT jsonb_build_object(
            'code', 'equipamiento_faltante', 'severity', 'error',
            'message', 'El espacio no cuenta con todo el equipamiento solicitado para esta clase.',
            'group', seccion.codigo, 'subject', asignatura.nombre, 'resource', recurso.nombre, 'room', aula.codigo
        )
        FROM required_resources AS requerido
        JOIN public.horarios AS horario ON horario.id_horario = requerido.id_horario
        JOIN public.recursos AS recurso ON recurso.id_recurso = requerido.id_recurso
        JOIN public.secciones AS seccion ON seccion.id_seccion = horario.id_seccion
        JOIN public.asignaturas AS asignatura ON asignatura.id_asignatura = horario.id_asignatura
        JOIN public.aulas AS aula ON aula.id_aula = horario.id_aula
        WHERE NOT EXISTS (
            SELECT 1 FROM public.aula_recurso AS disponible
            WHERE disponible.id_aula = requerido.id_aula AND disponible.id_recurso = requerido.id_recurso
        )
        ORDER BY seccion.codigo, asignatura.nombre, recurso.nombre
    LOOP issues := issues || jsonb_build_array(issue); END LOOP;

    FOR issue IN
        SELECT jsonb_build_object(
            'code', 'sede_incompatible', 'severity', 'error',
            'message', CASE WHEN NULLIF(btrim(seccion.sede), '') IS NULL THEN 'El grupo no tiene sede y no puede validarse contra el inventario.' ELSE 'El espacio pertenece a una sede distinta a la registrada para el grupo.' END,
            'group', seccion.codigo, 'group_site', seccion.sede, 'room', aula.codigo, 'room_site', pabellon.sede
        )
        FROM public.horarios AS horario
        JOIN public.secciones AS seccion ON seccion.id_seccion = horario.id_seccion
        JOIN public.aulas AS aula ON aula.id_aula = horario.id_aula
        JOIN public.pabellones AS pabellon ON pabellon.id_pabellon = aula.id_pabellon
        WHERE horario.id_version_horario = p_version_id
          AND (NULLIF(btrim(seccion.sede), '') IS NULL OR lower(btrim(seccion.sede)) <> lower(btrim(pabellon.sede)))
        ORDER BY seccion.codigo, aula.codigo
    LOOP issues := issues || jsonb_build_array(issue); END LOOP;

    FOR issue IN
        SELECT jsonb_build_object(
            'code', 'espacio_especializado_incompatible', 'severity', 'error',
            'message', 'El tipo del espacio no coincide con la necesidad especializada registrada.',
            'group', seccion.codigo, 'subject', asignatura.nombre,
            'requested', componente.observacion_espacio, 'room', aula.codigo, 'room_type', aula.tipo
        )
        FROM public.horarios AS horario
        JOIN public.asignacion_componentes AS componente ON componente.id_componente = horario.id_componente
        JOIN public.secciones AS seccion ON seccion.id_seccion = horario.id_seccion
        JOIN public.asignaturas AS asignatura ON asignatura.id_asignatura = horario.id_asignatura
        JOIN public.aulas AS aula ON aula.id_aula = horario.id_aula
        WHERE horario.id_version_horario = p_version_id AND componente.requiere_espacio_especializado
          AND (NULLIF(btrim(aula.tipo), '') IS NULL
            OR (lower(aula.tipo) NOT LIKE '%' || lower(btrim(componente.observacion_espacio)) || '%'
                AND lower(btrim(componente.observacion_espacio)) NOT LIKE '%' || lower(btrim(aula.tipo)) || '%'))
        ORDER BY seccion.codigo, asignatura.nombre
    LOOP issues := issues || jsonb_build_array(issue); END LOOP;

    FOR issue IN
        SELECT jsonb_build_object(
            'code', 'traslado_sabado_no_autorizado', 'severity', 'error',
            'message', 'El traslado excepcional solo puede ser al sábado y debe estar autorizado para las sedes de este período.',
            'group', seccion.codigo, 'day', bloque.dia, 'start', bloque.hora_inicio, 'end', bloque.hora_fin
        )
        FROM public.horarios AS horario
        JOIN public.bloques_clase AS bloque ON bloque.id_bloque = horario.id_bloque
        JOIN public.secciones AS seccion ON seccion.id_seccion = horario.id_seccion
        WHERE horario.id_version_horario = p_version_id AND horario.traslado_sabado
          AND (bloque.dia <> 'Sabado'
            OR NOT EXISTS (
                SELECT 1 FROM public.versiones_reglas_planificacion AS rules
                WHERE rules.id_periodo = target_period AND rules.numero_version = (
                    SELECT MAX(latest.numero_version) FROM public.versiones_reglas_planificacion AS latest WHERE latest.id_periodo = target_period
                ) AND COALESCE((rules.reglas->>'traslado_sabado_libre')::BOOLEAN, FALSE)
            )
            OR NOT (
                EXISTS (SELECT 1 FROM public.secciones WHERE id_periodo = target_period AND sede ILIKE '%CUR%')
                AND EXISTS (SELECT 1 FROM public.secciones WHERE id_periodo = target_period AND sede ILIKE '%instituto%')
            ))
        ORDER BY seccion.codigo, bloque.dia, bloque.hora_inicio
    LOOP issues := issues || jsonb_build_array(issue); END LOOP;

    -- A block is an error; missing an authorized preference is a warning.
    FOR issue IN
        SELECT jsonb_build_object(
            'code', CASE WHEN restriccion.condicion = 'bloqueo' THEN 'restriccion_incumplida' ELSE 'preferencia_no_cumplida' END,
            'severity', CASE WHEN restriccion.condicion = 'bloqueo' THEN 'error' ELSE 'warning' END,
            'message', CASE WHEN restriccion.condicion = 'bloqueo' THEN 'La clase incumple una restricción autorizada.' ELSE 'La clase no coincide con una preferencia comunicada.' END,
            'group', seccion.codigo, 'subject', asignatura.nombre, 'teacher', usuario.nombre,
            'restriction', restriccion.detalle, 'day', COALESCE(horario.dia_snapshot, bloque.dia),
            'start', COALESCE(horario.hora_inicio_snapshot, bloque.hora_inicio), 'end', COALESCE(horario.hora_fin_snapshot, bloque.hora_fin)
        )
        FROM public.horarios AS horario
        JOIN public.bloques_clase AS bloque ON bloque.id_bloque = horario.id_bloque
        JOIN public.secciones AS seccion ON seccion.id_seccion = horario.id_seccion
        JOIN public.asignaturas AS asignatura ON asignatura.id_asignatura = horario.id_asignatura
        JOIN public.restricciones_planificacion AS restriccion
          ON restriccion.id_periodo = bloque.id_periodo AND restriccion.id_carrera = seccion.id_carrera
        LEFT JOIN public.usuarios AS usuario ON usuario.id_usuario = restriccion.id_afectado AND restriccion.tipo_afectado = 'docente'
        WHERE horario.id_version_horario = p_version_id
          AND restriccion.condicion IN ('bloqueo', 'preferencia')
          AND CASE restriccion.tipo_afectado
              WHEN 'docente' THEN EXISTS (
                  SELECT 1 FROM public.horario_docente AS participante
                  WHERE participante.id_horario = horario.id_horario AND participante.id_docente = restriccion.id_afectado
              ) OR horario.id_docente = restriccion.id_afectado
              WHEN 'asignatura' THEN horario.id_asignatura = restriccion.id_afectado
              WHEN 'grupo' THEN horario.id_seccion = restriccion.id_afectado
              WHEN 'sede' THEN seccion.sede = COALESCE(restriccion.parametros->>'sede', '')
              WHEN 'carrera' THEN TRUE ELSE FALSE
          END
          AND (
              (restriccion.condicion = 'bloqueo'
               AND (restriccion.dia IS NULL OR restriccion.dia = COALESCE(horario.dia_snapshot, bloque.dia))
               AND (restriccion.hora_inicio IS NULL OR (restriccion.hora_inicio < COALESCE(horario.hora_fin_snapshot, bloque.hora_fin) AND restriccion.hora_fin > COALESCE(horario.hora_inicio_snapshot, bloque.hora_inicio))))
              OR (restriccion.condicion = 'preferencia'
                  AND (restriccion.dia IS NOT NULL OR restriccion.hora_inicio IS NOT NULL)
                  AND ((restriccion.dia IS NOT NULL AND restriccion.dia <> COALESCE(horario.dia_snapshot, bloque.dia))
                    OR (restriccion.hora_inicio IS NOT NULL AND NOT (restriccion.hora_inicio <= COALESCE(horario.hora_inicio_snapshot, bloque.hora_inicio) AND restriccion.hora_fin >= COALESCE(horario.hora_fin_snapshot, bloque.hora_fin)))))
          )
        ORDER BY bloque.dia, bloque.hora_inicio, seccion.codigo
    LOOP issues := issues || jsonb_build_array(issue); END LOOP;

    FOR restriction_row IN
        SELECT id_restriccion, id_carrera, detalle, parametros
        FROM public.restricciones_planificacion
        WHERE id_periodo = target_period AND condicion = 'juntas'
    LOOP
        SELECT COALESCE(array_agg(DISTINCT value::INTEGER), ARRAY[]::INTEGER[])
        INTO group_ids
        FROM jsonb_array_elements_text(restriction_row.parametros->'grupos') AS selected(value);
        SELECT COUNT(*) INTO matching_slot_count FROM (
            SELECT COALESCE(horario.dia_snapshot, bloque.dia) AS dia,
                   COALESCE(horario.hora_inicio_snapshot, bloque.hora_inicio) AS hora_inicio,
                   COALESCE(horario.hora_fin_snapshot, bloque.hora_fin) AS hora_fin
            FROM public.horarios AS horario
            JOIN public.bloques_clase AS bloque ON bloque.id_bloque = horario.id_bloque
            JOIN public.secciones AS seccion ON seccion.id_seccion = horario.id_seccion
            WHERE horario.id_version_horario = p_version_id
              AND seccion.id_carrera = restriction_row.id_carrera
              AND horario.id_seccion = ANY(group_ids)
            GROUP BY COALESCE(horario.dia_snapshot, bloque.dia), COALESCE(horario.hora_inicio_snapshot, bloque.hora_inicio), COALESCE(horario.hora_fin_snapshot, bloque.hora_fin)
            HAVING COUNT(DISTINCT horario.id_seccion) = pg_catalog.cardinality(group_ids)
        ) AS matching_slots;
        IF matching_slot_count = 0 THEN
            issues := issues || jsonb_build_array(jsonb_build_object(
                'code', 'clases_no_estan_juntas', 'severity', 'error',
                'message', 'Los grupos indicados no tienen una clase simultánea en la propuesta.',
                'restriction', restriction_row.detalle, 'groups', to_jsonb(group_ids)
            ));
        END IF;
    END LOOP;

    FOR restriction_row IN
        SELECT detalle, id_carrera
        FROM public.restricciones_planificacion
        WHERE id_periodo = target_period AND condicion = 'distribucion'
    LOOP
        issues := issues || jsonb_build_array(jsonb_build_object(
            'code', 'distribucion_requiere_revision', 'severity', 'warning',
            'message', 'La distribución particular requiere comprobar el detalle comunicado.',
            'restriction', restriction_row.detalle, 'career_id', restriction_row.id_carrera
        ));
    END LOOP;

    -- Only internal gaps count; scheduled breaks are subtracted from the gap.
    FOR issue IN
        WITH ordered_classes AS (
            SELECT horario.id_seccion, seccion.codigo AS group_code, bloque.id_periodo,
                   COALESCE(horario.dia_snapshot, bloque.dia) AS dia, seccion.modalidad, seccion.turno,
                   COALESCE(horario.hora_fin_snapshot, bloque.hora_fin) AS previous_end,
                   LEAD(COALESCE(horario.hora_inicio_snapshot, bloque.hora_inicio)) OVER (
                       PARTITION BY horario.id_seccion, COALESCE(horario.dia_snapshot, bloque.dia)
                       ORDER BY COALESCE(horario.hora_inicio_snapshot, bloque.hora_inicio)
                   ) AS next_start
            FROM public.horarios AS horario
            JOIN public.secciones AS seccion ON seccion.id_seccion = horario.id_seccion
            JOIN public.bloques_clase AS bloque ON bloque.id_bloque = horario.id_bloque
            WHERE horario.id_version_horario = p_version_id AND NOT bloque.es_receso
        ), gaps AS (
            SELECT * FROM ordered_classes WHERE next_start IS NOT NULL AND next_start > previous_end
        ), gap_minutes AS (
            SELECT gap.*,
                   EXTRACT(EPOCH FROM (gap.next_start - gap.previous_end)) / 60 - COALESCE((
                       SELECT SUM(EXTRACT(EPOCH FROM (LEAST(receso.hora_fin, gap.next_start) - GREATEST(receso.hora_inicio, gap.previous_end))) / 60)
                       FROM public.bloques_clase AS receso
                       WHERE receso.id_periodo = gap.id_periodo AND receso.dia = gap.dia AND receso.modalidad = gap.modalidad AND receso.turno = gap.turno AND receso.es_receso
                         AND receso.hora_inicio < gap.next_start AND receso.hora_fin > gap.previous_end
                   ), 0) AS remaining_minutes
            FROM gaps AS gap
        )
        SELECT jsonb_build_object(
            'code', 'hueco_interno', 'severity', 'warning',
            'message', 'Hay un hueco interno entre clases del mismo grupo, descontando los recesos.',
            'group', gap.group_code, 'day', gap.dia,
            'start', gap.previous_end, 'end', gap.next_start, 'gap_minutes', gap.remaining_minutes
        )
        FROM gap_minutes AS gap
        WHERE gap.remaining_minutes > 0
        ORDER BY gap.dia, gap.previous_end
    LOOP issues := issues || jsonb_build_array(issue); END LOOP;

    SELECT COUNT(*) FILTER (WHERE value->>'severity' = 'error'),
           COUNT(*) FILTER (WHERE value->>'severity' = 'warning')
    INTO error_count, warning_count
    FROM jsonb_array_elements(issues) AS findings(value);
    validation_state := CASE WHEN error_count > 0 THEN 'invalida' WHEN warning_count > 0 THEN 'con_avisos' ELSE 'valida' END;
    INSERT INTO public.validaciones_horario (id_version_horario, estado, cantidad_errores, cantidad_avisos, hallazgos, validada_por)
    VALUES (p_version_id, validation_state, error_count, warning_count, issues, public.current_app_user_id());
    UPDATE public.versiones_horario
    SET estado_validacion = validation_state, fecha_actualizacion = pg_catalog.now()
    WHERE id_version_horario = p_version_id;
    INSERT INTO public.auditoria_cambios_horario (id_version_horario, accion, detalle, realizada_por)
    VALUES (p_version_id, 'validacion', jsonb_build_object('estado', validation_state, 'errores', error_count, 'avisos', warning_count), public.current_app_user_id());
    RETURN jsonb_build_object('id_version_horario', p_version_id, 'estado', validation_state,
        'errores', error_count, 'avisos', warning_count, 'hallazgos', issues);
END;
$$;
REVOKE ALL ON FUNCTION public.validate_schedule_version(INTEGER) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.validate_schedule_version(INTEGER) TO authenticated;

-- Keep schedule versions immutable when an institutional grid is edited.
-- The active draft receives the new block time and is revalidated; shared or
-- approved snapshots become stale, while the official version keeps its time.
CREATE OR REPLACE FUNCTION public.update_class_block_time(
    p_block_id INTEGER,
    p_start_time TIME,
    p_end_time TIME
)
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    draft_affected_count INTEGER := 0;
    block_period_id INTEGER;
BEGIN
    IF NOT public.is_active_admin() AND NOT public.is_active_planner() THEN
        RAISE EXCEPTION 'Only administration or planning can change an academic grid.' USING ERRCODE = '42501';
    END IF;
    IF p_start_time IS NULL OR p_end_time IS NULL OR p_start_time >= p_end_time THEN
        RAISE EXCEPTION 'The start time must be earlier than the end time.' USING ERRCODE = '22023';
    END IF;
    SELECT id_periodo INTO block_period_id FROM public.bloques_clase WHERE id_bloque = p_block_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'The selected block does not exist.' USING ERRCODE = '23503'; END IF;

    PERFORM pg_catalog.set_config('acaplan.allow_grid_revalidation', 'on', TRUE);
    UPDATE public.bloques_clase SET hora_inicio = p_start_time, hora_fin = p_end_time
    WHERE id_bloque = p_block_id;

    UPDATE public.horarios AS horario
    SET hora_inicio_snapshot = p_start_time, hora_fin_snapshot = p_end_time,
        fecha_actualizacion = pg_catalog.now()
    FROM public.versiones_horario AS version
    WHERE horario.id_bloque = p_block_id
      AND version.id_version_horario = horario.id_version_horario
      AND version.estado = 'borrador';
    GET DIAGNOSTICS draft_affected_count = ROW_COUNT;

    -- Re-run the database conflict check on every changed class. The transaction
    -- rolls back the whole grid change if another resource now overlaps.
    UPDATE public.horarios AS horario
    SET id_docente = horario.id_docente
    FROM public.versiones_horario AS version
    WHERE horario.id_bloque = p_block_id
      AND version.id_version_horario = horario.id_version_horario
      AND version.estado = 'borrador';

    UPDATE public.versiones_horario AS version
    SET estado_validacion = 'obsoleta', fecha_actualizacion = pg_catalog.now()
    WHERE version.id_periodo = block_period_id
      AND version.estado IN ('compartido', 'aprobado')
      AND EXISTS (
          SELECT 1 FROM public.horarios AS horario
          WHERE horario.id_version_horario = version.id_version_horario AND horario.id_bloque = p_block_id
      );
    RETURN draft_affected_count;
END;
$$;
REVOKE ALL ON FUNCTION public.update_class_block_time(INTEGER, TIME, TIME) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.update_class_block_time(INTEGER, TIME, TIME) TO authenticated;

CREATE OR REPLACE FUNCTION public.preview_class_block_revalidation(p_block_id INTEGER)
RETURNS TEXT[]
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    affected_classes TEXT[];
BEGIN
    IF NOT public.is_active_admin() AND NOT public.is_active_planner() THEN
        RAISE EXCEPTION 'Only administration or planning can inspect grid changes.' USING ERRCODE = '42501';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.bloques_clase WHERE id_bloque = p_block_id) THEN
        RAISE EXCEPTION 'The selected block does not exist.' USING ERRCODE = '23503';
    END IF;
    SELECT COALESCE(
        pg_catalog.array_agg(
            pg_catalog.format('%s · %s · V%s (%s)', seccion.codigo, asignatura.nombre, version.numero_version, version.estado)
            ORDER BY version.numero_version DESC, seccion.codigo, asignatura.nombre
        ), ARRAY[]::TEXT[]
    )
    INTO affected_classes
    FROM public.horarios AS horario
    JOIN public.versiones_horario AS version ON version.id_version_horario = horario.id_version_horario
    JOIN public.secciones AS seccion ON seccion.id_seccion = horario.id_seccion
    JOIN public.asignaturas AS asignatura ON asignatura.id_asignatura = horario.id_asignatura
    WHERE horario.id_bloque = p_block_id;
    RETURN affected_classes;
END;
$$;
REVOKE ALL ON FUNCTION public.preview_class_block_revalidation(INTEGER) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.preview_class_block_revalidation(INTEGER) TO authenticated;

COMMIT;
