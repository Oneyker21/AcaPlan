CREATE OR REPLACE FUNCTION public.remove_schedule_session(p_schedule_id INTEGER, p_confirm_fixed BOOLEAN DEFAULT FALSE, p_reason TEXT DEFAULT NULL)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    target_version INTEGER;
    was_fixed BOOLEAN;
BEGIN
    IF NOT public.is_active_admin() AND NOT public.is_active_planner() THEN
        RAISE EXCEPTION 'Only planning can remove classes from a draft.' USING ERRCODE = '42501';
    END IF;
    SELECT horario.id_version_horario, horario.es_fijada INTO target_version, was_fixed
    FROM public.horarios AS horario
    JOIN public.versiones_horario AS version ON version.id_version_horario = horario.id_version_horario
    WHERE horario.id_horario = p_schedule_id AND version.estado = 'borrador';
    IF NOT FOUND THEN RAISE EXCEPTION 'Only a class in the current draft can be removed.' USING ERRCODE = '23514'; END IF;
    IF was_fixed AND (NOT p_confirm_fixed OR NULLIF(btrim(p_reason), '') IS NULL OR length(btrim(p_reason)) > 300) THEN
        RAISE EXCEPTION 'Removing a fixed class needs explicit confirmation and a reason.' USING ERRCODE = '23514';
    END IF;
    INSERT INTO public.auditoria_cambios_horario (id_version_horario, id_horario, accion, detalle, realizada_por)
    VALUES (target_version, p_schedule_id, 'sesion_eliminada', jsonb_build_object('reason', COALESCE(p_reason, '')), public.current_app_user_id());
    DELETE FROM public.horarios WHERE id_horario = p_schedule_id;
END;
$$;

