CREATE TRIGGER reglas_invalidate_schedule_versions
    AFTER INSERT ON public.versiones_reglas_planificacion
    FOR EACH ROW EXECUTE FUNCTION public.invalidate_period_schedule_versions();

CREATE OR REPLACE FUNCTION public.validate_schedule_assignment()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    assignment_period INTEGER;
    assignment_day public.dias_semana;
    assignment_start TIME;
    assignment_end TIME;
    is_break BOOLEAN;
    version_state TEXT;
    is_copy BOOLEAN;
BEGIN
    PERFORM pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext('acaplan_schedule_conflicts'));
    is_copy := pg_catalog.current_setting('acaplan.allow_schedule_clone', TRUE) = 'on';

    SELECT bloque.id_periodo, COALESCE(NEW.dia_snapshot, bloque.dia),
           COALESCE(NEW.hora_inicio_snapshot, bloque.hora_inicio),
           COALESCE(NEW.hora_fin_snapshot, bloque.hora_fin), bloque.es_receso
    INTO assignment_period, assignment_day, assignment_start, assignment_end, is_break
    FROM public.bloques_clase AS bloque WHERE bloque.id_bloque = NEW.id_bloque;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'The selected class block does not exist.' USING ERRCODE = '23503';
    END IF;
    IF is_break THEN
        RAISE EXCEPTION 'A break block cannot be assigned to a class.' USING ERRCODE = '23514';
    END IF;
    SELECT version.estado INTO version_state
    FROM public.versiones_horario AS version
    WHERE version.id_version_horario = NEW.id_version_horario
      AND version.id_periodo = assignment_period;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'The class block and draft version must belong to the same period.' USING ERRCODE = '23514';
    END IF;
    IF pg_catalog.current_setting('acaplan.allow_schedule_publish', TRUE) = 'on'
       AND TG_OP = 'UPDATE' AND NEW.estado_publicacion = 'publicado'
       AND OLD.estado_publicacion IS DISTINCT FROM NEW.estado_publicacion
       AND NEW.id_docente IS NOT DISTINCT FROM OLD.id_docente
       AND NEW.id_asignatura IS NOT DISTINCT FROM OLD.id_asignatura
       AND NEW.id_seccion IS NOT DISTINCT FROM OLD.id_seccion
       AND NEW.id_aula IS NOT DISTINCT FROM OLD.id_aula
       AND NEW.id_bloque IS NOT DISTINCT FROM OLD.id_bloque
       AND NEW.id_version_horario IS NOT DISTINCT FROM OLD.id_version_horario
       AND NEW.id_componente IS NOT DISTINCT FROM OLD.id_componente
       AND NEW.numero_sesion IS NOT DISTINCT FROM OLD.numero_sesion THEN
        RETURN NEW;
    END IF;
    IF version_state <> 'borrador' AND NOT (
        version_state = 'archivado' AND is_copy
    ) THEN
        RAISE EXCEPTION 'Only a current draft can be changed.' USING ERRCODE = '23514';
    END IF;
    IF TG_OP = 'UPDATE' AND OLD.estado_publicacion = 'publicado'
       AND (NEW.id_docente IS DISTINCT FROM OLD.id_docente
         OR NEW.id_asignatura IS DISTINCT FROM OLD.id_asignatura
         OR NEW.id_seccion IS DISTINCT FROM OLD.id_seccion
         OR NEW.id_aula IS DISTINCT FROM OLD.id_aula
         OR NEW.id_bloque IS DISTINCT FROM OLD.id_bloque
         OR NEW.id_version_horario IS DISTINCT FROM OLD.id_version_horario
         OR NEW.id_componente IS DISTINCT FROM OLD.id_componente
         OR NEW.numero_sesion IS DISTINCT FROM OLD.numero_sesion) THEN
        RAISE EXCEPTION 'An official schedule cannot be edited; create a new draft.' USING ERRCODE = '23514';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM public.secciones AS seccion
        WHERE seccion.id_seccion = NEW.id_seccion AND seccion.id_periodo = assignment_period
    ) THEN
        RAISE EXCEPTION 'The class block and group must belong to the same period.' USING ERRCODE = '23514';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM public.seccion_asignatura AS linked
        WHERE linked.id_seccion = NEW.id_seccion AND linked.id_asignatura = NEW.id_asignatura
    ) THEN
        RAISE EXCEPTION 'The subject is not assigned to the selected group.' USING ERRCODE = '23514';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM public.docentes AS docente
        JOIN public.usuarios AS usuario ON usuario.id_usuario = docente.id_docente
        WHERE docente.id_docente = NEW.id_docente AND usuario.rol = 'docente' AND usuario.estado = 'activo'
    ) THEN
        RAISE EXCEPTION 'The selected teacher is not active.' USING ERRCODE = '23514';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.aulas WHERE id_aula = NEW.id_aula AND estado = 'activo') THEN
        RAISE EXCEPTION 'The selected room is not active.' USING ERRCODE = '23514';
    END IF;
    IF NEW.id_componente IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM public.asignacion_componentes AS componente
        JOIN public.asignaciones_academicas AS asignacion USING (id_asignacion_academica)
        WHERE componente.id_componente = NEW.id_componente
          AND asignacion.id_periodo = assignment_period
          AND asignacion.id_seccion = NEW.id_seccion
          AND asignacion.id_asignatura = NEW.id_asignatura
          AND NEW.numero_sesion BETWEEN 1 AND componente.sesiones_semana
    ) THEN
        RAISE EXCEPTION 'The scheduled session must match its official assignment and weekly session count.' USING ERRCODE = '23514';
    END IF;
    IF is_copy THEN RETURN NEW; END IF;

    IF EXISTS (
        SELECT 1 FROM public.horarios AS horario
        JOIN public.bloques_clase AS bloque ON bloque.id_bloque = horario.id_bloque
        WHERE horario.id_horario IS DISTINCT FROM NEW.id_horario
          AND horario.id_version_horario = NEW.id_version_horario
          AND bloque.id_periodo = assignment_period
          AND COALESCE(horario.dia_snapshot, bloque.dia) = assignment_day
          AND assignment_start < COALESCE(horario.hora_fin_snapshot, bloque.hora_fin)
          AND assignment_end > COALESCE(horario.hora_inicio_snapshot, bloque.hora_inicio)
          AND (horario.id_aula = NEW.id_aula OR horario.id_seccion = NEW.id_seccion)
    ) THEN
        RAISE EXCEPTION 'The selected group or room already has a class during this time in this draft.' USING ERRCODE = '23P01';
    END IF;
    IF EXISTS (
        SELECT 1 FROM public.restricciones_planificacion AS restriccion
        JOIN public.secciones AS seccion ON seccion.id_seccion = NEW.id_seccion
        WHERE restriccion.id_periodo = assignment_period
          AND restriccion.id_carrera = seccion.id_carrera
          AND restriccion.condicion = 'bloqueo'
          AND (restriccion.dia IS NULL OR restriccion.dia = assignment_day)
          AND (restriccion.hora_inicio IS NULL OR (restriccion.hora_inicio < assignment_end AND restriccion.hora_fin > assignment_start))
          AND CASE restriccion.tipo_afectado
              WHEN 'docente' THEN restriccion.id_afectado = NEW.id_docente
              WHEN 'asignatura' THEN restriccion.id_afectado = NEW.id_asignatura
              WHEN 'grupo' THEN restriccion.id_afectado = NEW.id_seccion
              WHEN 'sede' THEN seccion.sede = COALESCE(restriccion.parametros->>'sede', '')
              WHEN 'carrera' THEN TRUE
              ELSE FALSE
          END
    ) THEN
        RAISE EXCEPTION 'This class violates an authorized planning restriction.' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.create_schedule_draft(p_period_id INTEGER, p_base_version_id INTEGER DEFAULT NULL)
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    next_number INTEGER;
    new_version_id INTEGER;
    base_state TEXT;
    source_item RECORD;
    copied_schedule_id INTEGER;
    active_rules_version INTEGER;
BEGIN
    IF NOT public.is_active_admin() AND NOT public.is_active_planner() THEN
        RAISE EXCEPTION 'Only planning can create schedule drafts.' USING ERRCODE = '42501';
    END IF;
    PERFORM pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext('acaplan_period_' || p_period_id::TEXT));
    IF NOT EXISTS (SELECT 1 FROM public.periodos WHERE id_periodo = p_period_id) THEN
        RAISE EXCEPTION 'The selected period does not exist.' USING ERRCODE = '23503';
    END IF;
    IF p_base_version_id IS NOT NULL THEN
        SELECT estado INTO base_state FROM public.versiones_horario
        WHERE id_version_horario = p_base_version_id AND id_periodo = p_period_id;
        IF NOT FOUND OR base_state NOT IN ('borrador', 'compartido', 'aprobado', 'publicado', 'archivado') THEN
            RAISE EXCEPTION 'Choose a schedule version from the selected period.' USING ERRCODE = '23514';
        END IF;
    END IF;
    SELECT COALESCE(MAX(numero_version), 0) + 1 INTO next_number
    FROM public.versiones_horario WHERE id_periodo = p_period_id;
    SELECT id_version_reglas INTO active_rules_version
    FROM public.versiones_reglas_planificacion
    WHERE id_periodo = p_period_id ORDER BY numero_version DESC LIMIT 1;

    IF base_state = 'borrador' THEN
        UPDATE public.versiones_horario SET estado = 'archivado', fecha_actualizacion = pg_catalog.now()
        WHERE id_version_horario = p_base_version_id;
    END IF;
    INSERT INTO public.versiones_horario (
        id_periodo, numero_version, estado, estado_validacion, reglas_version_id,
        version_base_id, creada_por
    ) VALUES (
        p_period_id, next_number, 'borrador', 'pendiente', active_rules_version,
        p_base_version_id, public.current_app_user_id()
    ) RETURNING id_version_horario INTO new_version_id;

    IF p_base_version_id IS NOT NULL THEN
        PERFORM pg_catalog.set_config('acaplan.allow_schedule_clone', 'on', TRUE);
        FOR source_item IN
            SELECT * FROM public.horarios WHERE id_version_horario = p_base_version_id ORDER BY id_horario
        LOOP
            INSERT INTO public.horarios (
                id_docente, id_asignatura, id_seccion, id_aula, id_bloque,
                estado_publicacion, id_version_horario, id_componente, numero_sesion, es_fijada, traslado_sabado,
                dia_snapshot, hora_inicio_snapshot, hora_fin_snapshot
            ) VALUES (
                source_item.id_docente, source_item.id_asignatura, source_item.id_seccion,
                source_item.id_aula, source_item.id_bloque, 'borrador', new_version_id,
                source_item.id_componente, source_item.numero_sesion, source_item.es_fijada, source_item.traslado_sabado,
                source_item.dia_snapshot, source_item.hora_inicio_snapshot, source_item.hora_fin_snapshot
            ) RETURNING id_horario INTO copied_schedule_id;
            INSERT INTO public.horario_docente (id_horario, id_docente)
            SELECT copied_schedule_id, participant.id_docente
            FROM public.horario_docente AS participant
            WHERE participant.id_horario = source_item.id_horario
            ON CONFLICT DO NOTHING;
        END LOOP;
        PERFORM pg_catalog.set_config('acaplan.allow_schedule_clone', 'off', TRUE);
    END IF;
    INSERT INTO public.auditoria_cambios_horario (id_version_horario, accion, detalle, realizada_por)
    VALUES (new_version_id, 'borrador_creado', jsonb_build_object('version_base_id', p_base_version_id), public.current_app_user_id());
    RETURN new_version_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.save_schedule_session(
    p_version_id INTEGER,
    p_component_id INTEGER,
    p_session_number INTEGER,
    p_block_id INTEGER,
    p_room_id INTEGER,
    p_is_saturday_transfer BOOLEAN DEFAULT FALSE,
    p_confirm_fixed_move BOOLEAN DEFAULT FALSE,
    p_reason TEXT DEFAULT NULL
)
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    period_id INTEGER;
    section_id INTEGER;
    subject_id INTEGER;
    session_count INTEGER;
    duration_minutes INTEGER;
    teacher_ids INTEGER[];
    lead_teacher INTEGER;
    schedule_id INTEGER;
    was_fixed BOOLEAN := FALSE;
    old_block_id INTEGER;
    old_room_id INTEGER;
    saturday_enabled BOOLEAN := FALSE;
BEGIN
    IF NOT public.is_active_admin() AND NOT public.is_active_planner() THEN
        RAISE EXCEPTION 'Only planning can edit schedule drafts.' USING ERRCODE = '42501';
    END IF;
    PERFORM pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext('acaplan_schedule_conflicts'));
    SELECT id_periodo INTO period_id FROM public.versiones_horario
    WHERE id_version_horario = p_version_id AND estado = 'borrador' FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Only an active draft can be edited.' USING ERRCODE = '23514'; END IF;
    SELECT asignacion.id_seccion, asignacion.id_asignatura, componente.sesiones_semana, componente.duracion_minutos
    INTO section_id, subject_id, session_count, duration_minutes
    FROM public.asignacion_componentes AS componente
    JOIN public.asignaciones_academicas AS asignacion USING (id_asignacion_academica)
    WHERE componente.id_componente = p_component_id AND asignacion.id_periodo = period_id;
    IF NOT FOUND OR p_session_number NOT BETWEEN 1 AND session_count THEN
        RAISE EXCEPTION 'Select an official class assignment and one of its weekly sessions.' USING ERRCODE = '23514';
    END IF;
    SELECT COALESCE(array_agg(id_docente ORDER BY id_docente), ARRAY[]::INTEGER[])
    INTO teacher_ids FROM public.asignacion_componente_docente WHERE id_componente = p_component_id;
    IF pg_catalog.cardinality(teacher_ids) = 0 THEN
        RAISE EXCEPTION 'The class assignment has no active teacher.' USING ERRCODE = '23514';
    END IF;
    lead_teacher := teacher_ids[1];
    IF NOT EXISTS (
        SELECT 1 FROM public.bloques_clase AS bloque
        WHERE bloque.id_bloque = p_block_id AND bloque.id_periodo = period_id
          AND NOT bloque.es_receso
          AND EXTRACT(EPOCH FROM (bloque.hora_fin - bloque.hora_inicio)) / 60 = duration_minutes
    ) THEN
        RAISE EXCEPTION 'Choose a class block in this period with the assigned session duration.' USING ERRCODE = '23514';
    END IF;
    IF p_is_saturday_transfer THEN
        SELECT COALESCE((
            SELECT (rules.reglas->>'traslado_sabado_libre')::BOOLEAN
            FROM public.versiones_reglas_planificacion AS rules
            WHERE rules.id_periodo = period_id ORDER BY rules.numero_version DESC LIMIT 1
        ), FALSE)
        INTO saturday_enabled
        ;
        IF NOT saturday_enabled OR NOT EXISTS (
            SELECT 1 FROM public.bloques_clase AS block WHERE block.id_bloque = p_block_id AND block.dia = 'Sabado'
        ) OR NOT (
            EXISTS (SELECT 1 FROM public.secciones WHERE id_periodo = period_id AND sede ILIKE '%CUR%')
            AND EXISTS (SELECT 1 FROM public.secciones WHERE id_periodo = period_id AND sede ILIKE '%instituto%')
        ) THEN
            RAISE EXCEPTION 'A Saturday transfer is allowed only when enabled for a period with both CUR and Instituto groups.' USING ERRCODE = '23514';
        END IF;
    END IF;
    SELECT id_horario, es_fijada, id_bloque, id_aula INTO schedule_id, was_fixed, old_block_id, old_room_id
    FROM public.horarios
    WHERE id_version_horario = p_version_id AND id_componente = p_component_id AND numero_sesion = p_session_number;
    IF was_fixed AND (old_block_id IS DISTINCT FROM p_block_id OR old_room_id IS DISTINCT FROM p_room_id) THEN
        IF NOT p_confirm_fixed_move OR NULLIF(btrim(p_reason), '') IS NULL OR length(btrim(p_reason)) > 300 THEN
            RAISE EXCEPTION 'A fixed class needs explicit confirmation and a reason before moving.' USING ERRCODE = '23514';
        END IF;
    END IF;
    INSERT INTO public.horarios (
        id_docente, id_asignatura, id_seccion, id_aula, id_bloque,
        estado_publicacion, id_version_horario, id_componente, numero_sesion, es_fijada, traslado_sabado
    ) VALUES (
        lead_teacher, subject_id, section_id, p_room_id, p_block_id,
        'borrador', p_version_id, p_component_id, p_session_number, COALESCE(was_fixed, FALSE), p_is_saturday_transfer
    )
    ON CONFLICT (id_version_horario, id_componente, numero_sesion)
        WHERE id_componente IS NOT NULL AND numero_sesion IS NOT NULL
    DO UPDATE SET id_docente = EXCLUDED.id_docente,
                  id_asignatura = EXCLUDED.id_asignatura,
                  id_seccion = EXCLUDED.id_seccion,
                  id_aula = EXCLUDED.id_aula,
                  id_bloque = EXCLUDED.id_bloque,
                  traslado_sabado = EXCLUDED.traslado_sabado,
                  fecha_actualizacion = pg_catalog.now()
    RETURNING id_horario INTO schedule_id;
    DELETE FROM public.horario_docente WHERE id_horario = schedule_id;
    INSERT INTO public.horario_docente (id_horario, id_docente)
    SELECT schedule_id, selected.id_docente FROM pg_catalog.unnest(teacher_ids) AS selected(id_docente)
    ON CONFLICT DO NOTHING;
    IF was_fixed AND (old_block_id IS DISTINCT FROM p_block_id OR old_room_id IS DISTINCT FROM p_room_id) THEN
        INSERT INTO public.auditoria_cambios_horario (id_version_horario, id_horario, accion, detalle, realizada_por)
        VALUES (p_version_id, schedule_id, 'movimiento_autorizado', jsonb_build_object(
            'reason', btrim(p_reason), 'old_block_id', old_block_id, 'new_block_id', p_block_id,
            'old_room_id', old_room_id, 'new_room_id', p_room_id
        ), public.current_app_user_id());
    END IF;
    RETURN schedule_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.set_schedule_item_fixed(p_schedule_id INTEGER, p_fixed BOOLEAN)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    target_version INTEGER;
BEGIN
    IF NOT public.is_active_admin() AND NOT public.is_active_planner() THEN
