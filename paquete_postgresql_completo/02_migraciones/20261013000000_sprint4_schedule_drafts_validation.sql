CREATE OR REPLACE FUNCTION public.set_schedule_time_snapshot()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.dia_snapshot IS NULL OR NEW.hora_inicio_snapshot IS NULL OR NEW.hora_fin_snapshot IS NULL THEN
            SELECT bloque.dia, bloque.hora_inicio, bloque.hora_fin
            INTO NEW.dia_snapshot, NEW.hora_inicio_snapshot, NEW.hora_fin_snapshot
            FROM public.bloques_clase AS bloque WHERE bloque.id_bloque = NEW.id_bloque;
        END IF;
    ELSIF NEW.id_bloque IS DISTINCT FROM OLD.id_bloque THEN
        SELECT bloque.dia, bloque.hora_inicio, bloque.hora_fin
        INTO NEW.dia_snapshot, NEW.hora_inicio_snapshot, NEW.hora_fin_snapshot
        FROM public.bloques_clase AS bloque WHERE bloque.id_bloque = NEW.id_bloque;
    END IF;
    IF NEW.dia_snapshot IS NULL OR NEW.hora_inicio_snapshot IS NULL OR NEW.hora_fin_snapshot IS NULL THEN
        RAISE EXCEPTION 'Every scheduled class must retain its day and time.' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
