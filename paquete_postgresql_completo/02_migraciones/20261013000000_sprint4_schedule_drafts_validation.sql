CREATE OR REPLACE FUNCTION public.validate_schedule_teacher_link()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    slot_period INTEGER;
    slot_day public.dias_semana;
    slot_start TIME;
    slot_end TIME;
    version_id INTEGER;
    is_copy BOOLEAN;
BEGIN
    is_copy := pg_catalog.current_setting('acaplan.allow_schedule_clone', TRUE) = 'on';
    SELECT bloque.id_periodo, COALESCE(horario.dia_snapshot, bloque.dia),
           COALESCE(horario.hora_inicio_snapshot, bloque.hora_inicio),
           COALESCE(horario.hora_fin_snapshot, bloque.hora_fin), horario.id_version_horario
    INTO slot_period, slot_day, slot_start, slot_end, version_id
    FROM public.horarios AS horario
    JOIN public.bloques_clase AS bloque ON bloque.id_bloque = horario.id_bloque
    WHERE horario.id_horario = NEW.id_horario;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'The selected schedule class does not exist.' USING ERRCODE = '23503';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM public.docentes AS docente
        JOIN public.usuarios AS usuario ON usuario.id_usuario = docente.id_docente
        WHERE docente.id_docente = NEW.id_docente AND usuario.rol = 'docente' AND usuario.estado = 'activo'
    ) THEN
        RAISE EXCEPTION 'Only active official teachers can participate in a class.' USING ERRCODE = '23514';
    END IF;
    IF is_copy THEN RETURN NEW; END IF;
    IF EXISTS (
        SELECT 1
        FROM public.horarios AS other
        JOIN public.bloques_clase AS other_block ON other_block.id_bloque = other.id_bloque
        WHERE other.id_horario <> NEW.id_horario
          AND other.id_version_horario = version_id
          AND other_block.id_periodo = slot_period
          AND COALESCE(other.dia_snapshot, other_block.dia) = slot_day
          AND slot_start < COALESCE(other.hora_fin_snapshot, other_block.hora_fin)
          AND slot_end > COALESCE(other.hora_inicio_snapshot, other_block.hora_inicio)
          AND (
              other.id_docente = NEW.id_docente
              OR EXISTS (SELECT 1 FROM public.horario_docente AS other_teacher WHERE other_teacher.id_horario = other.id_horario AND other_teacher.id_docente = NEW.id_docente)
          )
    ) THEN
        RAISE EXCEPTION 'This teacher already has a class during this time in the current draft.' USING ERRCODE = '23P01';
    END IF;
    IF EXISTS (
        SELECT 1
        FROM public.horarios AS horario
        JOIN public.bloques_clase AS bloque ON bloque.id_bloque = horario.id_bloque
        JOIN public.secciones AS seccion ON seccion.id_seccion = horario.id_seccion
        JOIN public.restricciones_planificacion AS restriccion
          ON restriccion.id_periodo = bloque.id_periodo AND restriccion.id_carrera = seccion.id_carrera
        WHERE horario.id_horario = NEW.id_horario
          AND restriccion.condicion = 'bloqueo'
          AND restriccion.tipo_afectado = 'docente'
          AND restriccion.id_afectado = NEW.id_docente
          AND (restriccion.dia IS NULL OR restriccion.dia = COALESCE(horario.dia_snapshot, bloque.dia))
          AND (restriccion.hora_inicio IS NULL OR (restriccion.hora_inicio < COALESCE(horario.hora_fin_snapshot, bloque.hora_fin) AND restriccion.hora_fin > COALESCE(horario.hora_inicio_snapshot, bloque.hora_inicio)))
    ) THEN
        RAISE EXCEPTION 'This teacher has an authorized restriction during this time.' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS horario_docente_no_overlap ON public.horario_docente;
CREATE TRIGGER horario_docente_no_overlap
    BEFORE INSERT OR UPDATE OF id_horario, id_docente ON public.horario_docente
    FOR EACH ROW EXECUTE FUNCTION public.validate_schedule_teacher_link();

-- Restriction changes invalidate relevant working versions without changing
-- their state or discarding the draft. Rule and assignment triggers are added
-- after their final write functions below.
CREATE OR REPLACE FUNCTION public.mark_schedule_version_pending()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    changed_version INTEGER;
BEGIN
    IF TG_OP = 'DELETE' THEN
        changed_version := OLD.id_version_horario;
    ELSE
        changed_version := NEW.id_version_horario;
    END IF;
    UPDATE public.versiones_horario
    SET estado_validacion = 'pendiente', fecha_actualizacion = pg_catalog.now()
    WHERE id_version_horario = changed_version
      AND estado IN ('borrador', 'compartido', 'aprobado');
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS horarios_version_mark_pending ON public.horarios;
CREATE TRIGGER horarios_version_mark_pending
    AFTER INSERT OR UPDATE OR DELETE ON public.horarios
    FOR EACH ROW EXECUTE FUNCTION public.mark_schedule_version_pending();

DROP TRIGGER IF EXISTS restricciones_invalidate_schedule_versions ON public.restricciones_planificacion;
CREATE OR REPLACE FUNCTION public.invalidate_period_schedule_versions()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    target_period INTEGER;
BEGIN
    IF TG_OP = 'DELETE' THEN
        target_period := OLD.id_periodo;
    ELSE
